def _build_run(review_run_id: str, extraction_run_id: str):
    """One synthetic "run" -- an AIUseEvent, a screening batch it produced,
    a selection decision it produced, and a map-answer/claim pair anchored
    to `extraction_run_id`. Two runs built from DIFFERENT run-scoped ids but
    otherwise identical content must collapse to an identical shape once
    `pair_canonical_ids` substitutes each run's own ids for the other's."""
    event = build_ai_use_event(
        review_run_id=review_run_id, stage="title_abstract_screening",
        work_item_id="title_abstract_screening:batchfp-0001", attempt=0,
        tool_kind="llm", model="gpt-4o-mini", provider="openai",
        component_versions={"slr_pipeline": "0.1.0"}, task_purpose="screen batch",
        model_config_id="mc-1", input_artifact_refs=["record:rec-0001"],
        output_artifact_refs=["screenbatch:screenbatch-x"], call_status="success",
        prompt_template_version="v1", prompt_template_text="Screen: {{records}}",
        rendered_prompt_hash="a" * 64,
        timestamp="2026-01-01T00:00:00Z",
    )
    batch = build_screening_batch_result(
        review_run_id=review_run_id, stage="title_abstract_screening",
        batch_fingerprint="batchfp-0001", record_ids=["rec-0001"],
        producing_event_id=event.event_id, call_status="success",
        responses=[ScreeningResponse(decision="include", reason="on-topic", relevant_topics=[], confidence=0.9)],
    )
    source_event_id = derive_source_event_id(
        producer_artifact_id=event.event_id, record_id="rec-0001", stage="title_abstract_screening",
    )
    decision_id = "00000000-0000-4000-8000-00000000000" + ("1" if review_run_id.endswith("a") else "2")
    decision = build_selection_decision_record(
        review_run_id=review_run_id, decision_id=decision_id, source_event_id=source_event_id,
        record_id="rec-0001", stage="title_abstract_screening", decision="include",
        decision_maker="ai", producer_artifact_id=event.event_id, timestamp="2026-01-01T00:00:00Z",
    )
    ev_ref = EvidenceReference(
        artifact_kind="extraction", artifact_run_id=extraction_run_id, record_id="rec-0001",
        field_id="population",
        evidence_id=make_evidence_id(
            artifact_kind="extraction", artifact_run_id=extraction_run_id, record_id="rec-0001",
            field_id="population", chunk_id="chunk-1", quotation="adults with diabetes",
            page="4", section="Methods", locator="p4s1",
        ),
    )
    answer = build_map_answer(
        rq_or_section="RQ1", record_id="rec-0001", answer_text="Adults with diabetes were included.",
        selectors=[SupportingFieldSelector(artifact_kind="extraction", field_id="population")],
        evidence_references=[ev_ref], producing_event_id=event.event_id,
    )
    claim = build_synthesis_claim(
        claim_text="Most included studies enrolled adults with diabetes.",
        contributing_answers=[answer], rq_or_section="RQ1", producing_event_id=event.event_id,
    )
    return {"event": event, "batch": batch, "decision": decision, "answer": answer, "claim": claim}


def _canonicalize(obj, id_map):
    """Recursively substitute run-scoped ids for their `CID:*` placeholder,
    using string containment (ids like `answer_id`/`claim_id`/`event_id`
    are themselves derived FROM the run id, so they change too -- but not
    via a single substring swap, hence they are compared post-hoc via
    DERIVATIONS instead of being canonicalized here)."""
    if isinstance(obj, dict):
        return {k: _canonicalize(v, id_map) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_canonicalize(v, id_map) for v in obj]
    if isinstance(obj, str) and obj in id_map:
        return id_map[obj]
    return obj


def test_projection_fk_isomorphism():
    """Two independent "runs" over the identical logical content, differing
    only in their run-scoped identity strings, must be structurally
    identical (record -> answer -> claim -> evidence -> run FK graph) once
    each run's own ids are canonicalised to the shared `CID:*` placeholders
    (plan §8.4, points 1-2 -- decision-chain pairing, points 3-5, is out of
    scope here per this module's own docstring)."""
    run_a = _build_run("review-run-fk-a", "extraction-run-fk-a")
    run_b = _build_run("review-run-fk-b", "extraction-run-fk-b")

    identity_a = RunIdentity(review_run_id="review-run-fk-a", extraction_run_id="extraction-run-fk-a")
    identity_b = RunIdentity(review_run_id="review-run-fk-b", extraction_run_id="extraction-run-fk-b")
    pairs = pair_canonical_ids(identity_a, identity_b)
    assert pairs == {"review-run-fk-a": "review-run-fk-b", "extraction-run-fk-a": "extraction-run-fk-b"}

    map_a = canonicalize_run_ids(identity_a)
    map_b = canonicalize_run_ids(identity_b)
    assert set(map_a.values()) == set(map_b.values()) == {"CID:run", "CID:extraction_run"}

    canon_a = _canonicalize(
        {"event": run_a["event"].model_dump(mode="json"), "batch": run_a["batch"].model_dump(mode="json"),
         "decision": run_a["decision"].model_dump(mode="json")},
        map_a,
    )
    canon_b = _canonicalize(
        {"event": run_b["event"].model_dump(mode="json"), "batch": run_b["batch"].model_dump(mode="json"),
         "decision": run_b["decision"].model_dump(mode="json")},
        map_b,
    )
    # Run-scoped ids are canonicalised away above; derived ids (event_id,
    # work_item_id/artifact_id/batch_fingerprint, source_event_id/
    # decision_id) are content-addressed FROM those run ids and so still
    # legitimately differ byte-for-byte between the two runs -- masking
    # them out here is exactly what the real two-run comparison (step 16)
    # will also have to do, per plan §8.4's own "derived_id"/"canonical_id"
    # split. What's asserted is that after BOTH substitutions, the two
    # runs are the same graph shape.
    def _mask_derived(obj):
        if isinstance(obj, dict):
            return {
                k: ("<masked>" if k in {
                    "event_id", "work_item_id", "artifact_id", "batch_fingerprint",
                    "source_event_id", "decision_id", "content_hash", "semantic_hash",
                    "prompt_template_hash", "producer_artifact_id", "producing_event_id",
                } else _mask_derived(v))
                for k, v in obj.items()
            }
        if isinstance(obj, list):
            return [_mask_derived(v) for v in obj]
        return obj

    assert _mask_derived(canon_a) == _mask_derived(canon_b)

    # And the derivations themselves recompute correctly per run (proving
    # the "difference" masked above really is only the run-scoped inputs,
    # not an actual content mismatch): each run's own event_id/work_item_id
    # verify against ITS OWN run id, and cross-checking run A's inputs
    # against run B's ids does NOT accidentally also validate.
    assert run_a["event"].event_id == compute_event_id(
        review_run_id="review-run-fk-a", stage="title_abstract_screening",
        work_item_id="title_abstract_screening:batchfp-0001", attempt=0,
    )
    assert run_a["event"].event_id != compute_event_id(
        review_run_id="review-run-fk-b", stage="title_abstract_screening",
        work_item_id="title_abstract_screening:batchfp-0001", attempt=0,
    )

    # FK chain within a single run resolves end-to-end: claim ->
    # supporting_answer_ids -> answer.answer_id, and answer's own
    # evidence_references -> real evidence_ids, symmetrically for both runs.
    for run in (run_a, run_b):
        assert run["claim"].supporting_answer_ids == [run["answer"].answer_id]
        assert run["answer"].evidence_references[0].evidence_id.startswith("evidence-")
        assert run["batch"].producing_event_id == run["event"].event_id
        assert run["decision"].producer_artifact_id == run["event"].event_id


